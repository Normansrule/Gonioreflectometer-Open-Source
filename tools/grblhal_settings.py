#!/usr/bin/env python3
"""grblHAL $-settings for the BTT SKR Pico, generated from software/config/machine.yaml.

    python tools/grblhal_settings.py            # write firmware/grblhal/settings.txt
    python tools/grblhal_settings.py --check    # exit 1 if the file is stale

Setting numbers: grblHAL core settings.h / Trinamic plugin README [R83][R84]. Axis map: X = M4, Y = M3, Z = M2, A = M1
(controller letters from machine.yaml). Units are degrees: steps_per_mm is used as steps per degree. With $22 bit 3
("force set origin") each axis reads 0 on its switch; the software adds home_deg (gantry.Gantry._zero).

SPDX-License-Identifier: GPL-3.0-or-later
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "software" / "src"))
from opengonio.gantry.config import load_config  # noqa: E402

OUT = ROOT / "firmware" / "grblhal" / "settings.txt"
LETTERS = "XYZA"
# Per axis: max rate (deg/min), acceleration (deg/s^2), run current (mA), hold current (% of run). Same motion as the
# FluidNC config these replace (firmware/fluidnc/config.yaml); currents for the 17HS4401 (1.5 A) and the 1 A pancake.
DRIVE = {"M4": (900, 30, 800, 50), "M3": (1800, 60, 800, 50), "M2": (900, 40, 800, 50), "M1": (1800, 60, 700, 50)}
HOMING_FEED, HOMING_SEEK, DEBOUNCE_MS, PULLOFF_DEG = 30, 300, 250, 2.0


def settings() -> list[tuple[str, str, str]]:
    cfg = load_config()
    axes = sorted(cfg.axes.items(), key=lambda kv: LETTERS.index(kv[1].fluidnc_axis))
    mask = sum(1 << LETTERS.index(a.fluidnc_axis) for _, a in axes)
    rows = [
        ("$1", "255", "step idle delay: 255 = motors stay energised between poses (hold torque)"),
        ("$5", "0", "limit inputs not inverted (optical endstop low = triggered); set the axis bit if `?` shows Pn while clear"),
        ("$10", "17", "status report: machine position (1) + pin state Pn (16), as the software parses"),
        ("$20", "1", "soft limits on (needs homing)"),
        ("$21", "0", "hard limits off: one switch per axis, at the home end; the J3 over-travel switch cuts motor power"),
        ("$22", "15", "homing: enable (1) + single-axis $HX (2) + Alarm until homed (4) + 0 at the switch (8)"),
        ("$23", str(mask), "home every axis in the negative direction (switches at the range minimum)"),
        ("$24", str(HOMING_FEED), "homing locate rate, deg/min"),
        ("$25", str(HOMING_SEEK), "homing search rate, deg/min"),
        ("$26", str(DEBOUNCE_MS), "homing debounce, ms"),
        ("$27", f"{PULLOFF_DEG:g}", "homing pull-off, deg"),
        ("$62", "1", "sleep enable: `$SLP` = opengonio sleep (leave with a reset, then re-home)"),
    ]
    for n, (_, a) in enumerate(axes, start=1):
        rows.append((f"${43 + n}", str(1 << LETTERS.index(a.fluidnc_axis)), f"homing cycle {n}: {a.fluidnc_axis} only ($H homes one axis at a time)"))
    for k, a in axes:
        i = LETTERS.index(a.fluidnc_axis)
        rate, acc, ma, hold = DRIVE[k]
        if a.home_deg != a.min_deg:
            raise SystemExit(f"{k}: grblHAL settings assume the switch at min_deg (home_deg {a.home_deg} != min_deg {a.min_deg})")
        rows += [(f"${100 + i}", f"{a.steps_per_deg:.3f}", f"{a.fluidnc_axis} = {k} {a.name}: steps per degree (gear {a.gear_ratio:g}, 1/{a.microsteps})"),
                 (f"${110 + i}", str(rate), f"{a.fluidnc_axis} max rate, deg/min"),
                 (f"${120 + i}", str(acc), f"{a.fluidnc_axis} acceleration, deg/s^2"),
                 (f"${130 + i}", f"{a.max_deg - a.min_deg:g}", f"{a.fluidnc_axis} travel, deg ({a.min_deg:g} to {a.max_deg:g})"),
                 (f"${140 + i}", str(ma), f"{a.fluidnc_axis} motor current, mA RMS (SKR Pico: add the fan above 800 mA)"),
                 (f"${150 + i}", str(a.microsteps), f"{a.fluidnc_axis} microsteps"),
                 (f"${210 + i}", str(hold), f"{a.fluidnc_axis} hold current, % of run current")]
    return rows


def render() -> str:
    head = ["; OpenGonio - grblHAL settings for the BTT SKR Pico V1.0 (generated by tools/grblhal_settings.py: edit",
            "; machine.yaml or the tool, then `make build`). Send with: bash scripts/controller.sh settings",
            "; Lines starting with ';' are comments. Setting numbers: grblHAL core + Trinamic plugin [R83][R84].", ""]
    return "\n".join(head + [f"{k}={v}    ; {c}" for k, v, c in settings()]) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    txt = render()
    if a.check:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == txt
        print("grblHAL settings current" if ok else f"stale: {OUT.relative_to(ROOT)} (run make build)")
        return 0 if ok else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(txt, encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(settings())} settings")
    return 0


if __name__ == "__main__":
    sys.exit(main())
