#!/usr/bin/env python3
"""Tables and figures for the paper, generated from the repo so the manuscript never drifts from the design.

    python tools/paper_assets.py            tables -> paper/generated/*.tex (no extra packages)
    python tools/paper_assets.py --figures  also figures -> paper/figures/ (needs cadquery, matplotlib, cairosvg)

Tables: HardwareX specifications, design files summary (every printed part), bill of materials summary (core parts).
Figures: shaded render of cad/assembly (white background); light versions of docs/assets/axes.svg, architecture.svg.
SPDX-License-Identifier: GPL-3.0-or-later
"""
from __future__ import annotations

import argparse
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GEN, FIG = ROOT / "paper" / "generated", ROOT / "paper" / "figures"
sys.path.insert(0, str(ROOT / "tools"))
import bom_check  # noqa: E402

LIGHT = {"#0d1117": "#ffffff", "#161b22": "#f4f4f4", "#30363d": "#bbbbbb", "#f0f6fc": "#111111",
         "#c9d1d9": "#222222", "#8b949e": "#555555"}


def tex(s: str) -> str:
    s = s.replace("\\", "/")
    for a, b in (("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"), ("_", r"\_"), ("~", r"\textasciitilde{}"),
                 ("^", r"\textasciicircum{}"), ("≥", r"$\geq$"), ("≤", r"$\leq$"), ("×", r"$\times$"), ("±", r"$\pm$"),
                 ("°", r"\textdegree{}"), ("µ", r"\textmu{}"), ("Ø", r"\O{}"), ("→", r"$\rightarrow$")):
        s = s.replace(a, b)
    return s


def rows():
    for f in sorted((ROOT / "phases").glob("*/bom.csv")):
        for r in csv.DictReader(f.open(newline="", encoding="utf-8")):
            yield f.parent.name, r


def total(kind: str) -> float:
    return sum(float(r["Total USD"] or 0) for _, r in rows() if r["Type"] == kind)


def specs() -> str:
    core = total("Purchase")
    items = [("Hardware name", "Open Source Gonioreflectometer"),
             ("Subject area", "Engineering and materials science; computer graphics (material appearance)"),
             ("Hardware type", "Measuring physical properties and in-lab sensors; imaging tools"),
             ("Closest commercial analog", "Laboratory gonioreflectometers and goniospectrophotometers"),
             ("Open source license", "Hardware CERN-OHL-S-2.0; software GPL-3.0-or-later; documentation CC BY-SA 4.0"),
             ("Cost of hardware", f"US\\${core:,.2f} in parts (cap US\\${bom_check.HARD_CAP:,.0f}); tools US\\${total('Tool'):,.2f}"),
             ("Source file repository", r"\url{https://github.com/Normansrule/Gonioreflectometer-Open-Source} (DOI at release)")]
    body = "\n".join(f"{a} & {b} \\\\ \\hline" for a, b in items)
    return ("% generated by tools/paper_assets.py\n\\begin{tabularx}{\\linewidth}{|l|X|}\\hline\n" + body + "\n\\end{tabularx}\n")


def design_files() -> str:
    L = []
    for stl in sorted((ROOT / "phases").glob("*/3d/*.stl")):
        pid, _, name = stl.stem.partition("_")
        rel = stl.relative_to(ROOT).parent.parent.name             # stage folder; files are in its 3d/
        L.append(f"{tex(pid)} {tex(name.replace('_', ' '))} & STEP, STL & CERN-OHL-S-2.0 & \\path{{{rel}}} \\\\")
    L += [r"Bought-part stand-ins & STEP, STL & CERN-OHL-S-2.0 & \path{cad/bought} \\",
          r"Whole-machine assembly & STEP & CERN-OHL-S-2.0 & \path{cad/assembly} \\",
          r"CAD source (CadQuery) & Python & GPL-3.0-or-later & \path{tools/cad} \\"]
    head = (r"{\small\begin{longtable}{|p{0.34\linewidth}|l|l|l|}\caption{Design files summary. Printed parts: \texttt{phases/<stage>/3d/}, STEP and STL.}\label{tab:design}\\\hline"
            "\n\\textbf{Design file} & \\textbf{Type} & \\textbf{License} & \\textbf{Location} \\\\ \\hline\\endfirsthead\n"
            "\\hline\\textbf{Design file} & \\textbf{Type} & \\textbf{License} & \\textbf{Location} \\\\ \\hline\\endhead\n")
    return "% generated by tools/paper_assets.py\n" + head + "\n".join(L) + "\n\\hline\\end{longtable}}\n"


BOMHEAD = ("\\textbf{Designator} & \\textbf{Component} & \\textbf{No.} & \\textbf{Unit} & \\textbf{Total} & "
           "\\textbf{Source} \\\\ \\hline")


def bom() -> str:
    L = []
    for _, r in rows():
        if r["Type"] != "Purchase" or float(r["Total USD"] or 0) == 0:
            continue
        L.append(" & ".join([tex(r["ID"]), tex(r["Part"]), r["Qty"], f"{float(r['Unit USD']):.2f}", f"{float(r['Total USD']):.2f}",
                             tex(r["Supplier"])]) + r" \\")
    head = (r"{\small\begin{longtable}{|l|p{0.43\linewidth}|r|r|r|l|}\caption{Bill of materials summary (core machine; "
            r"shared packs counted once; prices in USD, checked on the store pages).}\label{tab:bom}\\\hline"
            "\n" + BOMHEAD + "\\endfirsthead\n\\hline" + BOMHEAD + "\\endhead\n")
    foot = f"\\hline\\multicolumn{{4}}{{|r|}}{{\\textbf{{Total}}}} & \\textbf{{{total('Purchase'):,.2f}}} & \\multicolumn{{1}}{{l|}}{{}} \\\\ \\hline\n"
    return "% generated by tools/paper_assets.py\n" + head + "\n".join(L) + "\n" + foot + "\\end{longtable}}\n"


def plain(longtable_tex: str) -> str:
    """Same table as a plain tabular without caption/heads (pandoc reads it for the Word copy)."""
    body = longtable_tex.split("\\endhead\n", 1)[1].split("\\end{longtable}")[0]
    head = re.search(r"\\endfirsthead\n\\hline(.*?)\\endhead", longtable_tex, re.S).group(1)
    ncol = head.count("&") + 1
    body = body.replace(r"\multicolumn{4}{|r|}{\textbf{Total}}", r" & & & \textbf{Total}").replace(r"\multicolumn{1}{l|}{}", "")
    spec = "lp{0.45\\linewidth}rrrl" if ncol == 6 else "p{0.35\\linewidth}lll"
    body = body.replace("\\path{", "\\texttt{")
    return ("% generated by tools/paper_assets.py (plain copy for pandoc / Word)\n\\begin{tabular}{" + spec + "}\n"
            + head.strip() + "\n" + body.replace("\\hline", "") + "\\end{tabular}\n")


def numbers() -> str:
    """Macros the text uses, so figures in the prose follow the repo."""
    n_print = len(list((ROOT / "phases").glob("*/3d/*.stl")))
    n_buy = sum(1 for _, r in rows() if r["Type"] == "Purchase")
    grams = re.search(r"Core machine: ≈ (\d+) g", (ROOT / "cad" / "PRINT.md").read_text(encoding="utf-8"))
    return ("% generated by tools/paper_assets.py\n"
            f"\\newcommand{{\\costparts}}{{US\\${total('Purchase'):,.2f}}}\n"
            f"\\newcommand{{\\costtools}}{{US\\${total('Tool'):,.2f}}}\n"
            f"\\newcommand{{\\nprinted}}{{{n_print}}}\n\\newcommand{{\\nbought}}{{{n_buy}}}\n"
            f"\\newcommand{{\\abs}}{{{grams.group(1) if grams else '?'}}}\n")


def subdivide(t, c, edge: float):
    """Split triangles longer than `edge` (mm) into 4 until none is."""
    import numpy as np
    for _ in range(8):
        long = np.max(np.linalg.norm(t - np.roll(t, 1, axis=1), axis=2), axis=1) > edge
        if not long.any():
            break
        a, b, d = t[long, 0], t[long, 1], t[long, 2]
        ab, bd, da = (a + b) / 2, (b + d) / 2, (d + a) / 2
        new = np.concatenate([np.stack(x, 1) for x in ((a, ab, da), (ab, b, bd), (da, bd, d), (ab, bd, da))])
        t = np.concatenate([t[~long], new])
        c = np.concatenate([c[~long]] + [c[long]] * 4)
    return t, c


def figures() -> None:
    import cairosvg
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import numpy as np
    from mpl_toolkits.mplot3d.art3d import Poly3DCollection
    FIG.mkdir(parents=True, exist_ok=True)
    for name in ("axes", "architecture"):
        svg = (ROOT / "docs" / "assets" / f"{name}.svg").read_text(encoding="utf-8")
        for a, b in LIGHT.items():
            svg = svg.replace(a, b)
        svg = re.sub(r"\s*\[[A-Z]+\d+\]", "", svg)               # repo reference IDs: the paper cites in APA
        cairosvg.svg2pdf(bytestring=svg.encode(), write_to=str(FIG / f"{name}.pdf"))
        cairosvg.svg2png(bytestring=svg.encode(), write_to=str(FIG / f"{name}.png"), output_width=2000)   # Word / Google Docs
    sys.path.insert(0, str(ROOT / "tools" / "cad"))
    import assembly as A
    tris, cols = [], []
    for shape, _, loc, col in A.build():
        if shape is None:
            continue
        s = shape.moved(loc) if loc else shape
        v, f = s.tessellate(1.0, 0.4)
        v = np.array([[p.x, p.y, p.z] for p in v])
        c = col.toTuple()[:3] if col else (0.6, 0.6, 0.6)
        for t in f:
            tris.append(v[list(t)])
            cols.append(c)
    tris, cols = subdivide(np.array(tris), np.array(cols), 30.0)   # small triangles: matplotlib depth-sorts per triangle
    n = np.cross(tris[:, 1] - tris[:, 0], tris[:, 2] - tris[:, 0])
    n /= np.linalg.norm(n, axis=1)[:, None] + 1e-9
    shade = 0.45 + 0.55 * np.abs(n @ np.array([0.35, -0.55, 0.76]))
    fc = np.clip(np.array(cols) * shade[:, None], 0, 1)
    fig = plt.figure(figsize=(7, 5.5))
    ax = fig.add_subplot(projection="3d")
    ax.add_collection3d(Poly3DCollection(tris, facecolors=fc, edgecolors="none"))
    mn, mx = tris.reshape(-1, 3).min(0), tris.reshape(-1, 3).max(0)
    ax.set_xlim(mn[0], mx[0]); ax.set_ylim(mn[1], mx[1]); ax.set_zlim(mn[2], mx[2])
    ax.set_box_aspect(tuple(mx - mn), zoom=0.95); ax.view_init(24, -58); ax.set_axis_off()
    fig.subplots_adjust(0, 0, 1, 1)
    fig.savefig(FIG / "assembly.png", dpi=220, facecolor="white", bbox_inches="tight", pad_inches=0.05)
    plt.close(fig)
    from PIL import Image, ImageChops
    im = Image.open(FIG / "assembly.png").convert("RGB")
    box = ImageChops.difference(im, Image.new("RGB", im.size, "white")).getbbox()
    if box:
        pad = 20
        im.crop((max(box[0] - pad, 0), max(box[1] - pad, 0), min(box[2] + pad, im.width), min(box[3] + pad, im.height))).save(FIG / "assembly.png")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--figures", action="store_true")
    a = ap.parse_args()
    GEN.mkdir(parents=True, exist_ok=True)
    for name, fn in (("specs", specs), ("design_files", design_files), ("bom", bom), ("numbers", numbers)):
        text = fn()
        (GEN / f"{name}.tex").write_text(text, encoding="utf-8")
        if "longtable" in text:
            (GEN / f"{name}_plain.tex").write_text(plain(text), encoding="utf-8")
    if a.figures:
        figures()
    print("paper/generated: specs, design_files, bom, numbers" + (" + paper/figures" if a.figures else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
