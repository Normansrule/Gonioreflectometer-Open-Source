#!/usr/bin/env python3
"""Fixed-camera optics for both modes: thin lens, field of view, depth of field, diffraction [R1 Fig. 7].

Thin lens, Cartesian sign convention (as in [R1]):  1/p' - 1/p = 1/f   (p < 0 object side)
Magnification m = p'/p.  Airy disk diameter d = 2.44 lambda N; blur FWHM ~ 1.03 lambda N.
Depth of field (thin lens, m small):  DOF ~ 2 N c (1 + m) / m^2   (c = allowed blur circle).
  BRDF mode: c = 2 pixels (texture detail on a flat swatch).
  Scan mode: c = diffraction blur 1.03 lambda N (geometric blur never dominates).
Sensor size = camera width/height x pixel pitch from software/config/machine.yaml.
Writes phases/06-camera-light/optics.md.

SPDX-License-Identifier: GPL-3.0-or-later
"""
from __future__ import annotations

import math
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "phases" / "06-camera-light" / "optics.md"
CFG = yaml.safe_load((ROOT / "software" / "config" / "machine.yaml").read_text())
CAM = CFG["camera"]
PIXEL_UM = float(CAM["pixel_um"])
SENSOR_MM = (CAM["width"] * PIXEL_UM / 1000.0, CAM["height"] * PIXEL_UM / 1000.0)
LAMBDA_UM = 0.55


def image_distance(f_mm: float, object_mm: float) -> float:
    p = -abs(object_mm)
    return 1.0 / (1.0 / f_mm + 1.0 / p)


def magnification(f_mm: float, object_mm: float) -> float:
    p = -abs(object_mm)
    return abs(image_distance(f_mm, object_mm) / p)


def field_mm(f_mm: float, object_mm: float) -> tuple[float, float]:
    m = magnification(f_mm, object_mm)
    return SENSOR_MM[0] / m, SENSOR_MM[1] / m


def airy_um(n: float, lam_um: float = LAMBDA_UM) -> float:
    return 2.44 * lam_um * n


def blur_fwhm_um(n: float, lam_um: float = LAMBDA_UM) -> float:
    return 1.03 * lam_um * n


def dof_mm(f_mm: float, object_mm: float, n: float, coc_um: float = 2 * PIXEL_UM) -> float:
    m = magnification(f_mm, object_mm)
    return 2 * n * (coc_um / 1000.0) * (1 + m) / (m * m)


def scan_dof_mm(f_mm: float, object_mm: float, n: float, pixel_um: float = PIXEL_UM) -> float:
    """Depth of field with the blur circle matched to diffraction (at least 2 pixels)."""
    return dof_mm(f_mm, object_mm, n, max(2 * pixel_um, blur_fwhm_um(n)))


def resolution_mm(f_mm: float, object_mm: float, n: float) -> float:
    """Smallest resolvable detail on the object: sqrt(2) x max(2 px, diffraction blur), over m."""
    m = magnification(f_mm, object_mm)
    return math.sqrt(2) * max(2 * PIXEL_UM, blur_fwhm_um(n)) / 1000.0 / m


def needed_depth_mm(sample_mm: float, theta_r_deg: float) -> float:
    return sample_mm * math.sin(math.radians(theta_r_deg))


def report(f_mm: float = float(CAM["focal_length_mm"]), d_mm: float = 350.0, sample_mm: float = 50.0) -> str:
    m = magnification(f_mm, d_mm)
    fw, fh = field_mm(f_mm, d_mm)
    lines = [
        "# Fixed-camera optics (generated by tools/optics.py)", "",
        f"f = {f_mm} mm, {CAM['width']} x {CAM['height']} px at {PIXEL_UM} um "
        f"(sensor {SENSOR_MM[0]:.2f} x {SENSOR_MM[1]:.2f} mm).", "",
        "## BRDF mode (350 mm)", "",
        f"- Magnification {m:.4f}; field {fw:.0f} x {fh:.0f} mm; pixel footprint {PIXEL_UM / m:.0f} um.",
        f"- Depth needed for a {sample_mm:.0f} mm swatch: {needed_depth_mm(sample_mm, 60):.0f} mm at theta_r 60 deg.", "",
        "| Aperture N | Airy disk (um) | Airy / pixel | DOF (mm, c = 2 px) |", "|---:|---:|---:|---:|"]
    for n in (2.0, 2.8, 4.0, 5.6, 8.0, 11.0, 16.0):
        lines.append(f"| f/{n:g} | {airy_um(n):.1f} | {airy_um(n) / PIXEL_UM:.1f} | {dof_mm(f_mm, d_mm, n):.1f} |")
    lines += ["", "Swatch BRDF: f/8 (averaged regions). Texture detail: f/4 and theta_r <= 45 deg.", ""]
    ds = float(CFG["scan"]["camera_distance_mm"])
    ms = magnification(f_mm, ds)
    sw, sh = field_mm(f_mm, ds)
    lines += [f"## Scan mode ({ds:.0f} mm)", "",
              f"- Magnification {ms:.4f}; field {sw:.0f} x {sh:.0f} mm; pixel footprint {PIXEL_UM / ms / 1000:.3f} mm "
              "(footprint, not resolution: see table).", "",
              "| Aperture N | DOF (mm, c = diffraction) | Resolution on object (mm) |", "|---:|---:|---:|"]
    for n in (5.6, 8.0, 11.0, 16.0):
        lines.append(f"| f/{n:g} | {scan_dof_mm(f_mm, ds, n):.0f} | {resolution_mm(f_mm, ds, n):.2f} |")
    lines += ["", "Scanning uses f/8: ~0.25 mm detail with enough depth for objects ~110 mm deep. "
              "Printed aperture stop = f / N = 2.0 mm (same stop as BRDF mode)."]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    txt = report()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(txt, encoding="utf-8")
    print(txt)
