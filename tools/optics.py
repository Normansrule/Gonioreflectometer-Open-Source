#!/usr/bin/env python3
"""Fixed-camera optics: thin lens, field of view, depth of field, diffraction [R1 Fig. 7].

Thin lens, Cartesian sign convention (as in [R1]):  1/p' - 1/p = 1/f   (p < 0 object side)
Magnification m = p'/p.  Airy disk diameter d = 2.44 * lambda * N.
Depth of field (thin lens, m small):  DOF ~ 2 N c (1 + m) / m^2   (c = circle of confusion).
Writes docs/generated/optics.md.

SPDX-License-Identifier: GPL-3.0-or-later
"""
from __future__ import annotations

import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "generated" / "optics.md"

SENSOR_MM = (6.287, 4.712)     # IMX477 active area (1.55 um x 4056 x 3040)
PIXEL_UM = 1.55
LAMBDA_UM = 0.55


def image_distance(f_mm: float, object_mm: float) -> float:
    p = -abs(object_mm)
    return 1.0 / (1.0 / f_mm + 1.0 / p)


def magnification(f_mm: float, object_mm: float) -> float:
    p = -abs(object_mm)
    return abs(image_distance(f_mm, object_mm) / p)


def field_mm(f_mm: float, object_mm: float) -> tuple[float, float]:
    m = magnification(f_mm, object_mm)
    return SENSOR_MM[0] / m, SENSOR_MM[1] / m


def airy_um(n: float, lam_um: float = LAMBDA_UM) -> float:
    return 2.44 * lam_um * n


def dof_mm(f_mm: float, object_mm: float, n: float, coc_um: float = 2 * PIXEL_UM) -> float:
    m = magnification(f_mm, object_mm)
    return 2 * n * (coc_um / 1000.0) * (1 + m) / (m * m)


def needed_depth_mm(sample_mm: float, theta_r_deg: float) -> float:
    """Depth range of a flat sample of width sample_mm seen at theta_r from its normal."""
    return sample_mm * math.sin(math.radians(theta_r_deg))


def report(f_mm: float = 16.0, d_mm: float = 350.0, sample_mm: float = 50.0) -> str:
    m = magnification(f_mm, d_mm)
    fw, fh = field_mm(f_mm, d_mm)
    lines = [
        "# Fixed-camera optics (generated by tools/optics.py)", "",
        f"f = {f_mm} mm, distance = {d_mm} mm, IMX477 1.55 um pixels.", "",
        f"- Magnification {m:.4f}; field {fw:.0f} x {fh:.0f} mm; pixel footprint {PIXEL_UM / m:.0f} um on the sample.",
        f"- Depth needed for a {sample_mm:.0f} mm swatch: {needed_depth_mm(sample_mm, 60):.0f} mm at theta_r 60 deg, "
        f"{needed_depth_mm(sample_mm, 80):.0f} mm at 80 deg.", "",
        "| Aperture N | Airy disk (um) | Airy / pixel | DOF (mm, c = 2 px) |", "|---:|---:|---:|---:|"]
    for n in (2.0, 2.8, 4.0, 5.6, 8.0, 11.0, 16.0):
        lines.append(f"| f/{n:g} | {airy_um(n):.1f} | {airy_um(n) / PIXEL_UM:.1f} | {dof_mm(f_mm, d_mm, n):.1f} |")
    lines += ["", "Trade-off: depth of field wants a small aperture, diffraction wants a large one.",
              "- BRDF of a swatch (values averaged over a region): f/8-f/11, DOF 23-31 mm.",
              "- Fine SVBRDF / texture detail: f/4 and keep theta_r <= 45 deg, or focus-stack.",
              "- Printed aperture stop diameter = f / N (f/8 -> 2.0 mm, f/11 -> 1.45 mm)."]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    txt = report()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(txt, encoding="utf-8")
    print(txt)
