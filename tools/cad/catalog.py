#!/usr/bin/env python3
"""Write cad/README.md: one row per BOM item with its 3D model(s) in the repo, the real model's source and licence.
Fails if a bought part has no model at all (every part must at least have a dummy).

    python tools/cad/catalog.py           # write cad/README.md
    python tools/cad/catalog.py --check   # only check coverage

No cadquery needed: it only reads phases/*/bom.csv and the files in cad/ and phases/*/3d/.
SPDX-License-Identifier: GPL-3.0-or-later
"""
from __future__ import annotations

import ast
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CAD = ROOT / "cad"
OUT = CAD / "README.md"
NO_MODEL = {"Tool", "Owned"}          # tools, laptop
NO_MODEL_IDS = {"FIL-01"}   # filament


def aliases() -> dict[str, str]:
    src = (ROOT / "tools" / "cad" / "bought.py").read_text(encoding="utf-8")
    for node in ast.walk(ast.parse(src)):
        if isinstance(node, ast.Assign) and any(getattr(t, "id", "") == "ALIASES" for t in node.targets):
            return ast.literal_eval(node.value)
    return {}


def rel(p: Path) -> str:
    return "../" + p.relative_to(ROOT).as_posix()


def link(p: Path) -> str:
    return f"[`{p.name}`]({rel(p)})"


def rows():
    for f in sorted((ROOT / "phases").glob("*/bom.csv")):
        for r in csv.DictReader(f.open(newline="", encoding="utf-8")):
            yield f.parent.name, r


def classify(stage: str, r: dict, al: dict) -> tuple[list[Path], str, str]:
    """-> (files in repo, real-model source, status)."""
    pid, step = r["ID"], r["STEP"].strip()
    if r["Type"] == "Print":
        files = sorted((ROOT / "phases").glob(f"*/3d/{pid}*.step"))
        return files, "ours (`tools/cad/parts.py`)", "printed part" if files else "MISSING"
    if r["Type"] in NO_MODEL or pid in NO_MODEL_IDS:
        return [], "-", "no model needed (" + ("tool" if r["Type"] == "Tool" else "laptop" if r["Type"] == "Owned" else "filament") + ")"
    key = al.get(pid, pid)
    files = sorted((CAD / "bought").glob(f"{key}_*.step"))
    opened = [ROOT / p for p in re.findall(r"cad/open/[\w.-]+\.step", step) if (ROOT / p).exists()]
    url = re.search(r"https?://\S+", step)
    if opened:
        status, src = "open model", "in repo (`cad/open/`)"
    elif (url and "Drawing" not in step) or r["CAD license"].startswith("Vendor CAD"):
        status, src = "vendor model (download) + dummy", step
    elif step.startswith("Onshape Standard Content"):
        status, src = "Onshape Standard Content + dummy", step
    else:
        status, src = "**dummy only**", step or "None published"
    files = opened + files
    if not files:
        status = "MISSING"
    return files, src, status


def mdlink(s: str) -> str:
    s = s.replace("|", "/")
    return re.sub(r"(https?://[^\s;)]+)", lambda m: f"[{m.group(1).split('/')[2]}]({m.group(1)})", s)


def main(check_only: bool = False) -> int:
    al = aliases()
    table, missing, dummy_only, counts = {}, [], [], {}
    for stage, r in rows():
        files, src, status = classify(stage, r, al)
        counts[status.strip("*")] = counts.get(status.strip("*"), 0) + 1
        if status == "MISSING":
            missing.append(f"{stage}/{r['ID']}")
        if status == "**dummy only**":
            dummy_only.append(f"{r['ID']} {r['Part']}")
        table.setdefault(stage, []).append((r, files, src, status))
    if missing:
        print("no 3D model for: " + ", ".join(missing), file=sys.stderr)
    if check_only:
        return 1 if missing else 0

    L = ["# CAD models", "",
         "<!-- generated by tools/cad/catalog.py from phases/*/bom.csv - do not edit by hand -->", "",
         "Every part in the parts lists has a 3D model you can import into Onshape (Onshape accepts STEP and zip):", "",
         "| Folder | What | Made by | Licence |", "|---|---|---|---|",
         "| [`phases/NN/3d/`](../phases) | printed parts (STEP + STL), black ABS | `make parts` (`tools/cad/parts.py`) | CERN-OHL-S-2.0 |",
         "| [`cad/bought/`](bought) | dummy models of bought parts: true outside size, holes, shafts, connectors | `make cad` (`tools/cad/bought.py`) | CERN-OHL-S-2.0 |",
         "| [`cad/open/`](open) | real models with open licences (Adafruit, KiCad) | `tools/cad/fetch_open.py` | see below |",
         "| [`cad/assembly/`](assembly) | the whole machine as one STEP assembly (printed + dummies) | `make cad` (`tools/cad/assembly.py`) | CERN-OHL-S-2.0 |",
         "| `cad/vendor/` (not in git) | real vendor models (vendor licences: link only) | `bash scripts/get_cad.sh` | vendor terms |",
         "| [`cad/PRINT.md`](PRINT.md) | print list: count, size vs build volume, ABS grams per part | `make parts` (`tools/cad/printability.py`) | - |", "",
         "**Checked:** `make cad-check` (`tools/cad/interference.py`) finds no collision between any two parts in the shown pose or "
         "anywhere along each axis' travel (M4 20–324°, M3 a full turn, M2 ±90°), and no part in the sight lines from the measuring "
         "camera, the scan camera and the lamp to the sample. Run it after every CAD change.", "",
         "**Start in Onshape:** Create → Import → `cad/assembly/opengonio_assembly.step` (or `dist/opengonio-cad.zip` from `make cad-zip`, "
         "which holds every STEP). Units are millimetres. Origin: the deck top under the zero point; +X toward the camera, +Z up. "
         "Pose shown: light arm on +Y (M4 = 90°), table at 0 (M3), platter face up (M2 = 90°).", "",
         "**Dummies vs real models:** a dummy is a plain envelope built from the datasheet dimensions (source in `tools/cad/bought.py`). "
         "Where the vendor publishes a model, swap the dummy for the `cad/vendor/` file; the dummy's origin and axes follow the comment in "
         "`bought.py` so you can mate the real one in the same place. GT2 pulley (Adafruit 1253) has an 8 mm bore: set it to 5 mm in Onshape.", "",
         "## Coverage", "",
         "| Status | Rows |", "|---|---|"]
    L += [f"| {k} | {v} |" for k, v in sorted(counts.items())]
    L += ["", "**Dummy only - the maker of the listed part publishes no 3D model (generic parts, stock material, wires, belts). No swap needed: the dummy has the real outside size:** "
          + "; ".join(dummy_only) + ".", ""]
    for stage, items in table.items():
        L += [f"## {stage}", "", "| ID | Part | Type | 3D file(s) in the repo | Real model | Status |", "|---|---|---|---|---|---|"]
        for r, files, src, status in items:
            fl = "<br>".join(link(p) for p in files) or "-"
            L.append(f"| {r['ID']} | {r['Part'].replace('|', '/')} | {r['Type']} | {fl} | {mdlink(src)} | {status} |")
        L.append("")
    L += ["## Licences of `cad/open/`", "",
          "- Adafruit_CAD_Parts (`adafruit_*`): MIT, © Adafruit Industries. <https://github.com/adafruit/Adafruit_CAD_Parts>",
          "- KiCad packages3D (`kicad_*`): CC-BY-SA 4.0 with the KiCad libraries exception (using them in your design does not put the "
          "design under CC-BY-SA). <https://gitlab.com/kicad/libraries/kicad-packages3D>",
          "- Vendor models (`cad/vendor/`) are never committed: their terms do not allow redistribution, or state none.", ""]
    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"cad/README.md: {sum(len(v) for v in table.values())} rows, {len(dummy_only)} dummy only, {len(missing)} missing")
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
