#!/usr/bin/env python3
"""Print list for black ABS: every printed part's size vs the printer's build volume, how many to print, and an
estimate of filament (solid volume from the STL, 4 walls + 25 % infill, ABS 1.04 g/cm3). Writes cad/PRINT.md and
fails if an STL is not watertight or a part does not fit the minimum build volume in BOM TLS-01 (220 x 220 x 200 mm).

    python tools/cad/printability.py

Needs numpy-stl (installed with cadquery: see `make setup`). Estimates are +-25 %: the slicer has the real number.
SPDX-License-Identifier: CERN-OHL-S-2.0
"""
from __future__ import annotations

import logging
import re
import sys
from pathlib import Path

import numpy as np
from stl import mesh

logging.getLogger("stl").setLevel(logging.ERROR)

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "cad" / "PRINT.md"
BED = (220.0, 220.0, 200.0)        # TLS-01 requirement (the printer bought must meet it)
RHO = 1.04                         # g/cm3, ABS
SHELL = 1.2                        # mm: average skin over all faces (4 x 0.45 mm walls, 5 x 0.2 mm top/bottom)
INFILL = 0.25
SUPPLY = 2000.0                    # g, FIL-01 (2 x 1 kg)
OPTIONAL_STAGES = {"10-color", "15-standalone"}
OPTIONAL_PARTS = {"CAL-06c": "chrome balls CAL-03", "ENC-04a": "dowel drape ENC-01/03"}   # serve optional bought parts
REG = dict((m[0], (m[1], m[3])) for m in re.findall(
    r'"([A-Z]+-\d+[a-z]?)": \("([\w-]+)", "(\w+)", [^,]+(?:\([^)]*\))?, "([^"]+)"\)', (ROOT / "tools/cad/parts.py").read_text()))


def stats(stl: Path) -> tuple[np.ndarray, float, float, bool]:
    m = mesh.Mesh.from_file(str(stl))
    closed = bool(m.is_closed(exact=True))                    # watertight: slicers and the volume need it
    vol, _, _ = m.get_mass_properties()
    area = float(m.areas.sum())
    return m.max_ - m.min_, abs(vol), area, closed


def grams(vol: float, area: float) -> float:
    shell = min(vol, area * SHELL)
    return RHO * (shell + INFILL * (vol - shell)) / 1000.0


def fits(size: np.ndarray) -> bool:
    x, y, z = size
    flat = max(x, y) <= BED[0] and min(x, y) <= BED[1]
    diag = (x + y) / 2 ** 0.5 <= BED[0]                       # turned 45 deg on the bed
    return z <= BED[2] and (flat or diag)


def main() -> int:
    rows, bad = [], []
    for pid, (stage, what) in REG.items():
        stl = next((ROOT / "phases" / stage / "3d").glob(f"{pid}_*.stl"), None)
        if stl is None:
            bad.append(f"{pid}: no STL (run make parts)")
            continue
        size, vol, area, closed = stats(stl)
        if not closed:
            bad.append(f"{pid}: STL is not watertight")
        n = int(m.group(1)) if (m := re.search(r"print (\d+)", what, re.I)) else 1
        g = grams(vol, area)
        ok = fits(size)
        if not ok:
            bad.append(f"{pid}: {size[0]:.0f} x {size[1]:.0f} x {size[2]:.0f} mm does not fit {BED}")
        rows.append((stage, pid, stl.name, what, n, size, g, ok))
    optional = lambda r: r[0] in OPTIONAL_STAGES or r[1] in OPTIONAL_PARTS
    core = sum(r[4] * r[6] for r in rows if not optional(r))
    opt = sum(r[4] * r[6] for r in rows if optional(r))
    L = ["# Print list (black ABS)", "",
         "<!-- generated by tools/cad/printability.py - do not edit by hand -->", "",
         "Enclosed printer, nozzle 245–255 °C, bed 100–105 °C, fan ≤ 20 %, 0.2 mm layers, 4 walls, 25 % gyroid, brim on tall "
         "or long parts, door shut until cool; XY shrink compensation from the tolerance coupon (M03.3). Print in the "
         "orientation of the STL (flat face down). Filament is an estimate (±25 %): the slicer has the real number.", "",
         f"**Core machine: ≈ {core:.0f} g of ABS** ({core / SUPPLY * 100:.0f} % of the 2 kg FIL-01 supply; ±25 %, plus any "
         f"reprints) · optional add-ons (stages 10, 15, {', '.join(OPTIONAL_PARTS)}): ≈ {opt:.0f} g · minimum build volume {BED[0]:.0f} × {BED[1]:.0f} × {BED[2]:.0f} mm "
         f"(largest part: {max(rows, key=lambda r: r[5][2])[1]}, {max(r[5][2] for r in rows):.0f} mm tall).", "",
         "| Stage | ID | Part | Print | Size x × y × z (mm) | ≈ g each | ≈ g total | Fits |", "|---|---|---|---:|---|---:|---:|---|"]
    for stage, pid, name, what, n, size, g, ok in rows:
        tag = " (optional)" if optional((stage, pid)) else ""
        L.append(f"| {stage} | {pid}{tag} | [{what}](../phases/{stage}/3d/{name}) | {n} | {size[0]:.0f} × {size[1]:.0f} × {size[2]:.0f} "
                 f"| {g:.0f} | {n * g:.0f} | {'yes' if ok else '**NO**'} |")
    L += ["", f"Total all parts: ≈ {core + opt:.0f} g. Regenerate: `make parts` (or `python tools/cad/printability.py`).", ""]
    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"cad/PRINT.md: {len(rows)} parts, core ≈ {core:.0f} g ABS ({core / SUPPLY * 100:.0f} % of FIL-01), optional ≈ {opt:.0f} g")
    for b in bad:
        print("FAIL " + b, file=sys.stderr)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
