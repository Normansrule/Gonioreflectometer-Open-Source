#!/usr/bin/env python3
"""Final-machine power budget: typical, peak and idle watts, headroom, buck heat,
wall-plug efficiency. Reads data/power_loads.yaml, writes docs/generated/power_budget.md.

    python tools/power_budget.py            # print + write
    python tools/power_budget.py --check    # exit 1 if headroom < required

SPDX-License-Identifier: GPL-3.0-or-later
"""
from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / "data" / "power_loads.yaml"
OUTPUT = ROOT / "docs" / "generated" / "power_budget.md"
MODES = ("typical", "peak", "idle")


@dataclass
class Result:
    mode: str
    rail5_out_w: float      # power delivered on the 5 V rail
    rail5_in_w: float       # power the buck draws from 24 V
    buck_loss_w: float
    rail24_direct_w: float  # 24 V loads excluding the buck
    dc_total_w: float       # total drawn from the adapter's 24 V output
    wall_w: float
    adapter_loss_w: float

    @property
    def amps_24v(self) -> float:
        return self.dc_total_w / 24.0

    @property
    def amps_5v(self) -> float:
        return self.rail5_out_w / 5.0

    @property
    def useful_w(self) -> float:
        """Power that reaches loads (excludes buck and adapter losses)."""
        return self.rail5_out_w + self.rail24_direct_w

    @property
    def wall_efficiency(self) -> float:
        return self.useful_w / self.wall_w if self.wall_w else 0.0


def compute(cfg: dict) -> dict[str, Result]:
    sup, buck = cfg["supply"], cfg["buck"]
    eff_buck = {"typical": buck["efficiency_typical"], "peak": buck["efficiency_peak"], "idle": buck["efficiency_idle"]}
    eff_sup = {"typical": sup["efficiency_typical_load"], "peak": sup["efficiency_peak_load"], "idle": sup["efficiency_idle_load"]}
    out = {}
    for mode in MODES:
        key = f"{mode}_w"
        r5 = sum(l[key] for l in cfg["loads"] if l["rail"] == "5V")
        r24 = sum(l[key] for l in cfg["loads"] if l["rail"] == "24V")
        r5_in = r5 / eff_buck[mode]
        dc = r24 + r5_in
        wall = dc / eff_sup[mode] + (sup["no_load_watts"] if mode == "idle" else 0.0)
        out[mode] = Result(mode, r5, r5_in, r5_in - r5, r24, dc, wall, wall - dc)
    return out


def headroom(cfg: dict, res: dict[str, Result]) -> float:
    """Fraction of adapter capacity left at peak: (rated - peak) / peak."""
    peak = res["peak"].dc_total_w
    return (cfg["supply"]["rated_watts"] - peak) / peak


def render(cfg: dict, res: dict[str, Result]) -> str:
    sup, buck = cfg["supply"], cfg["buck"]
    hr = headroom(cfg, res)
    req = cfg["required_headroom"]
    lines = [
        "# Final-machine power budget (generated - do not edit)",
        "",
        f"Generated by `tools/power_budget.py` from `data/power_loads.yaml`. All six phases installed, Raspberry Pi 5 assumed (worst case).",
        "",
        "## Loads",
        "",
        "| Load | Rail | Phase | Typical W | Peak W | Idle W |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for l in cfg["loads"]:
        lines.append(f"| {l['name']} | {l['rail']} | {l['phase']} | {l['typical_w']:.2f} | {l['peak_w']:.2f} | {l['idle_w']:.2f} |")
    lines += ["", "## Totals", "", "| | Typical | Peak | Idle (sleep) |", "|---|---:|---:|---:|"]
    t, p, i = res["typical"], res["peak"], res["idle"]

    def row(label: str, f) -> None:
        lines.append(f"| {label} | {f(t)} | {f(p)} | {f(i)} |")

    row("5 V rail delivered", lambda r: f"{r.rail5_out_w:.1f} W ({r.amps_5v:.2f} A)")
    row(f"Buck loss ({buck['name']})", lambda r: f"{r.buck_loss_w:.2f} W")
    row("24 V direct loads", lambda r: f"{r.rail24_direct_w:.1f} W")
    row("Adapter DC output", lambda r: f"{r.dc_total_w:.1f} W ({r.amps_24v:.2f} A)")
    row("Adapter loss", lambda r: f"{r.adapter_loss_w:.1f} W")
    row("**Wall plug**", lambda r: f"**{r.wall_w:.1f} W**")
    row("Wall-plug efficiency (load W / wall W)", lambda r: f"{100 * r.wall_efficiency:.0f} %")
    verdict = "PASS" if hr >= req else "FAIL"
    buck_warn = p.amps_5v > buck["rated_amps"]
    lines += [
        "",
        f"**Headroom at peak:** adapter rated {sup['rated_watts']:.0f} W vs peak {p.dc_total_w:.1f} W "
        f"-> {100 * hr:.0f} % headroom above peak, {100 * (1 - p.dc_total_w / sup['rated_watts']):.0f} % of capacity unused "
        f"(required >= {100 * req:.0f} % headroom): **{verdict}**.",
        f"Peak current {p.amps_24v:.2f} A of 5.00 A available.",
        "",
        ("**Buck check - WARNING:** " if buck_warn else "**Buck check:** ")
        + f"5 V allocation peak {p.amps_5v:.2f} A against a {buck['rated_amps']} A rating"
        + (" - the allocation exceeds the rating. " if buck_warn else ". ") +
        "The allocation assumes the Pi drawing its full 5 A USB budget at the same moment the servo stalls; "
        "with no USB peripherals and `usb_max_current_enable` left off, the realistic peak is about "
        "13 W + 3.75 W = 16.8 W (3.4 A), 38 % below the rating. Keep USB loads off the Pi.",
        "",
        "Buck and adapter efficiencies are design estimates (see the YAML) and are replaced with bench numbers "
        "in the Power module acceptance test.",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if headroom is below the requirement")
    args = ap.parse_args(argv)
    cfg = yaml.safe_load(INPUT.read_text())
    res = compute(cfg)
    text = render(cfg, res)
    print(text)
    if not args.check:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(text, encoding="utf-8")
    return 0 if headroom(cfg, res) >= cfg["required_headroom"] else 1


if __name__ == "__main__":
    sys.exit(main())
